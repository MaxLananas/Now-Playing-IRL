    private static final Map<String,App> BY_WIN = new HashMap<>(), BY_LINUX = new HashMap<>();
    static { for (App a: APPS){ for(String p:a.windowsProcesses()) BY_WIN.put(p.toLowerCase(Locale.ROOT),a); for(String p:a.linuxPlayers()) BY_LINUX.put(p.toLowerCase(Locale.ROOT),a);} }
    public static App byWindowsProcess(String exe){ if(exe==null) return null; String k=exe.toLowerCase(Locale.ROOT).replace(".exe",""); return BY_WIN.get(k); }
    public static App byLinuxPlayer(String name){ if(name==null) return null; String n=name.toLowerCase(Locale.ROOT); for(var e:BY_LINUX.entrySet()) if(n.contains(e.getKey())) return e.getValue(); return null; }
    public static App byId(String id){ for(App a:APPS) if(a.id().equals(id)) return a; return null; }
